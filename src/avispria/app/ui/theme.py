"""The colour system of every Dīvi screen: one palette, light and dark, taken from the logo.

This module is the single source of truth. The desktop interface (NiceGUI) and the phone field
page both get their colours from it (the phone page's stylesheet is generated by
``scripts/field_page.py``), and a test checks the contrast of every pairing.

The logo's four colours (measured from ``branding/logo.png``) each have a meaning:

    Vegetation  green       #669762   primary: the main action, forest and canopy
    Agriculture yellow      #DBB241   highlight: attention that is not an error, fields and crops
    Urban       blue-grey   #7A96AA   secondary: the second action, built surfaces and roads
    Drone       slate       #47545E   ink: outlines and the dark parts of the logo

They are used as given wherever they are *fills*. Small text needs 4.5:1, which none of them
reaches against white or near-black, so labels on the fills are dark ink and small text on the
page uses a measured darker (light mode) or brighter (dark mode) shade of the same hue. Errors
need a colour of their own that means "stop": a brick red that sits with the logo's warm yellow.

Light: a pale lichen page and white cards. Dark: a forest-night page with the same three hues
glowing brighter for text and data overlays.
"""

from __future__ import annotations

from dataclasses import dataclass, fields


def _rgb(hex_colour: str) -> tuple[int, int, int]:
    h = hex_colour.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def mix(top: str, base: str, amount: float) -> str:
    """``amount`` (0 to 1) of ``top`` laid over ``base``, as a hex colour."""
    a, b = _rgb(top), _rgb(base)
    return "#" + "".join(
        f"{round(x * amount + y * (1 - amount)):02X}" for x, y in zip(a, b, strict=True)
    )


def _linear(channel: int) -> float:
    c = channel / 255
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hex_colour: str) -> float:
    r, g, b = (_linear(v) for v in _rgb(hex_colour))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(a: str, b: str) -> float:
    """WCAG contrast: 4.5 is the minimum for small text, 3 for large text and graphics."""
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


