# runs before the page is painted, so a dark phone never flashes light; same file on the phone page
THEME_BOOT_JS = """(function () {
  var stored = null;
  try { stored = localStorage.getItem("avispria.theme"); } catch (e) {}
  var dark = stored ? stored === "dark"
    : !!(window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches);
  document.documentElement.setAttribute("data-theme", dark ? "dark" : "light");
})();
"""


def _variables(p: Palette) -> str:
    lines = [
        f"  --{f.name.replace('_', '-')}: {getattr(p, f.name)};"
        for f in fields(p)
        if isinstance(getattr(p, f.name), str) and f.name != "name"
    ]
    lines.append(f"  color-scheme: {p.name};")
    return "\n".join(lines)


def _quasar(p: Palette) -> str:
    """Quasar's own colour names (buttons, badges, links, toggles).

    NiceGUI writes its default colours (a blue primary) straight onto ``<body>`` as an inline style
    when the page loads, which beats any ordinary rule; ``!important`` on the body is what wins.
    """
    pairs = {
        "primary": p.primary,
        "secondary": p.secondary,
        "accent": p.highlight,
        "positive": p.primary,
        "negative": p.danger,
        "warning": p.highlight,
        "info": p.secondary_text,
        "dark": p.surface,
        "dark-page": p.bg,
    }
    return "\n".join(f"  --q-{name}: {value} !important;" for name, value in pairs.items())


def tokens_css(*, quasar: bool = False) -> str:
    """CSS variables for both modes.

    Dark applies when the page says so (``data-theme="dark"``, set before painting from the saved
    choice or the phone's setting), when Quasar is in dark mode, and, without JavaScript, when the
    system prefers dark.
    """
    light, dark = _variables(LIGHT), _variables(DARK)
    css = (
        f":root {{\n{light}\n}}\n"
        f':root[data-theme="dark"],\nbody.body--dark {{\n{dark}\n}}\n'
        f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme]) {{\n"
        + "\n".join("  " + line for line in dark.splitlines())
        + "\n  }\n}\n"
    )
    if quasar:
        css += (
            f"body {{\n{_quasar(LIGHT)}\n}}\n"
            f':root[data-theme="dark"] body,\nbody.body--dark {{\n{_quasar(DARK)}\n}}\n'
            f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme]) body {{\n"
            + "\n".join("  " + line for line in _quasar(DARK).splitlines())
            + "\n  }\n}\n"
        )
    return css
