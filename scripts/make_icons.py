"""Write ``src/avispria/app/ui/assets/icons.css`` from Lucide's SVG files.

Run once after changing ``ICONS`` in ``src/avispria/app/ui/icons.py``:

    npm pack lucide-static@1.60.0 && tar xzf lucide-static-1.60.0.tgz
    uv run python scripts/make_icons.py package/icons

Each icon becomes a mask (stroke 1.5, square caps for the technical look) that the stylesheet
fills with the text colour. Lucide is ISC-licensed; its notice is kept at the top of the file.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from avispria.app.ui.icons import ICON_CLASS, ICONS, LEAFLET_ICONS  # noqa: E402

OUT = ROOT / "src" / "avispria" / "app" / "ui" / "assets" / "icons.css"
NOTICE = """/* Icons: Lucide (https://lucide.dev), ISC License.
   Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).
   All other copyright (c) for Lucide are held by Lucide Contributors 2022.
   Permission to use, copy, modify, and/or distribute this software for any purpose with or
   without fee is hereby granted, provided that the above copyright notice and this permission
   notice appear in all copies. THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL
   WARRANTIES WITH REGARD TO THIS SOFTWARE.
   Generated by scripts/make_icons.py: do not edit by hand. */
"""


def shape(svg: str) -> str:
    """The drawing inside one Lucide file, as a compact 1.5-stroke SVG."""
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, flags=re.S)
    if inner is None:
        raise ValueError("not an SVG file")
    body = re.sub(r"\s+", " ", inner.group(1)).replace(" />", "/>").strip()
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" '
        f'stroke-width="1.5" stroke-linecap="square" stroke-linejoin="miter">{body}</svg>'
    )


def css(icons_dir: Path) -> str:
    rules = [NOTICE]
    for lucide in sorted(set(ICONS.values())):
        svg = shape((icons_dir / f"{lucide}.svg").read_text(encoding="utf-8"))
        rules.append(
            f'.{ICON_CLASS}-{lucide} {{ --dv-i: url("data:image/svg+xml,{quote(svg)}"); }}'
        )
    for button, lucide in sorted(LEAFLET_ICONS.items()):
        svg = shape((icons_dir / f"{lucide}.svg").read_text(encoding="utf-8"))
        rules.append(f'a.{button} {{ --dv-i: url("data:image/svg+xml,{quote(svg)}"); }}')
    return "\n".join(rules) + "\n"


def main() -> None:
    OUT.write_text(css(Path(sys.argv[1])), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
